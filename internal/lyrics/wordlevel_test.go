package lyrics

import "testing"

/* --------------------------------------------------------------------------
   字级（逐字）歌词的识别与归一化
   --------------------------------------------------------------------------
   覆盖五种真实来源写法（增强 LRC / QRC / KRC / 网易云 klyric / YRC）：
   归一化结果必须是**同一种**格式（增强 LRC），否则前端、歌词工作台、
   缓存文件就要各认各的格式，改一处漏一处。
   -------------------------------------------------------------------------- */

func TestNormalizeWordLevel(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string
	}{
		{
			name: "增强 LRC：原样保留（只统一成毫秒精度）",
			in:   "[00:12.00]<00:12.00>你<00:12.30>好",
			want: "[00:12.00]<00:12.000>你<00:12.300>好",
		},
		{
			name: "QRC：(偏移,时长) 后缀标记转成绝对时刻",
			in:   "[12000,800]你(0,300)好(300,500)",
			want: "[00:12.00]<00:12.000>你<00:12.300>好",
		},
		{
			name: "KRC：<偏移,时长,音高> 前缀标记相对行首换算",
			in:   "[12000,800]<0,300,0>你<300,500,0>好",
			want: "[00:12.00]<00:12.000>你<00:12.300>好",
		},
		{
			name: "网易云 klyric：行内时间标签是字级（不是第二行）",
			in:   "[00:12.00]你[00:12.30]好",
			want: "[00:12.00]<00:12.000>你<00:12.300>好",
		},
		{
			name: "YRC：只有时间的行头 + 下一行逐词时间",
			in:   "[12000,598]\n[12000,300]你[12300,300]好",
			want: "[00:12.00]<00:12.000>你<00:12.300>好",
		},
		{
			name: "一行挂多个时间标签：展开后逐字时间整体平移",
			in:   "[00:10.00][01:00.00]<00:10.000>A<00:10.500>B",
			want: "[00:10.00]<00:10.000>A<00:10.500>B\n[01:00.00]<01:00.000>A<01:00.500>B",
		},
		{
			name: "字级与行级混排：两种都保留",
			in:   "[00:01.00]普通句\n[00:02.00]<00:02.000>逐<00:02.500>字句",
			want: "[00:01.00]普通句\n[00:02.00]<00:02.000>逐<00:02.500>字句",
		},
		{
			name: "正文里的数字对不是字级标记（(2019,2020) 不能被吃掉）",
			in:   "[00:10.00](2019,2020)发行纪念",
			want: "[00:10.00](2019,2020)发行纪念",
		},
		{
			name: "纯行级 LRC 走行级归一化（行为不变）",
			in:   "[00:03.00]第一句\n[00:07.50]第二句",
			want: "[00:03.00]第一句\n[00:07.50]第二句",
		},
		{
			name: "行时间被重新打过轴：逐字时间整体平移到行首（保住行内节奏）",
			in:   "[00:20.00]<00:12.000>你<00:12.300>好",
			want: "[00:20.00]<00:20.000>你<00:20.300>好",
		},
		{
			name: "完全没有时间轴的纯文本原样返回（不丢内容）",
			in:   "第一句\n第二句",
			want: "第一句\n第二句",
		},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := NormalizeWordLevel(c.in)
			if got != c.want {
				t.Fatalf("NormalizeWordLevel(%q) =\n%q\nwant\n%q", c.in, got, c.want)
			}
			// 幂等：归一化过的文本再跑一遍必须一模一样（否则缓存里存不下）
			if again := NormalizeWordLevel(got); again != got {
				t.Fatalf("幂等性失败：%q -> %q", got, again)
			}
		})
	}
}

// 字级文本写进歌曲文件之前必须剥成行级（逐字标记进了标签就是别家播放器的正文）。
func TestNormalizeWordLevelThenLineLevel(t *testing.T) {
	word := NormalizeWordLevel("[12000,800]你(0,300)好(300,500)")
	if line := NormalizeLineLevel(word); line != "[00:12.00]你好" {
		t.Fatalf("内嵌前应剥成行级，实际 %q", line)
	}
}

func TestHasWordTiming(t *testing.T) {
	wordish := []string{
		"[00:12.00]<00:12.00>你",              // 增强 LRC
		"[12000,800]<0,300,0>你",              // KRC
		"[12000,800]你(0,300)好",               // QRC
		"[00:12.00]你[00:12.30]好",             // 网易云 klyric
		"[12000,300]你[12300,300]好",           // YRC
		"[00:12.00]<00:12.000>你<00:12.300>好", // 归一化产物
	}
	for _, s := range wordish {
		if !HasWordTiming(s) {
			t.Errorf("HasWordTiming(%q) 应为 true", s)
		}
	}

	lineish := []string{
		"[00:12.00]普通行级歌词",
		"[12000,800]只有毫秒行标签（剥掉不丢任何逐字信息）",
		"[ar:某歌手]\n[00:10.00]正文",
		"没有时间轴的纯文本",
		"",
	}
	for _, s := range lineish {
		if HasWordTiming(s) {
			t.Errorf("HasWordTiming(%q) 应为 false", s)
		}
	}
}
