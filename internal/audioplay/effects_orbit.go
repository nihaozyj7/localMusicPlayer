/* ==========================================================================
   effects_orbit.go — 环绕档的运动调制（"音乐绕着头转圈"）
   --------------------------------------------------------------------------
   ★ 为什么需要这个文件（第五轮，用户反馈）

   第四轮把"双耳时间差"做出来了（早期反射场，见 effects_early.go），
   但用户听完还是不对：

       "你的这个音频是固定的，没有音乐环绕的感觉，
        3D 环绕脑袋里面会感觉音乐绕着在转圈圈，
        他这个左右两只耳机输出的声音是动态的"

   关键词是**动态**。前三轮+第四轮做的全部是**静态**处理：
   滤波器、延迟、混响参数一旦定下就不再变化，左右耳的输出比例
   是一条固定曲线。静态处理能改变"声场长什么样"，但改变不了
   "声场会不会动" —— 听感上就是"宽了、有空间了，但它不转"。

   真正的 3D 环绕（以及任何"绕着转"的听感）要求**双耳差异本身
   随时间变化**：声源方位 θ(t) 在动，于是

       ILD(t) ∝ sin θ(t)      左右耳强度差在摆
       ITD(t) ∝ sin θ(t)      左右耳到达时间差在摆

   两条线索一起动，大脑才会把声音归类成"它在动"，而不是"它很宽"。
   这个文件就是把这两条线索变成时间函数。

   --------------------------------------------------------------------------
   一、两个调制量，各自必须满足的硬约束

   ┌─ 摆动声像（ILD）──────────────────────────────────────────────┐
   │                                                                │
   │   L = mid·(1 + K·s) + side                                     │
   │   R = mid·(1 - K·s) - side                                     │
   │                                                                │
   │   ★★★ **单声道折叠逐位不变**：L + R = 2·mid 恒成立，         │
   │   与 s 取什么值无关。这不是"调小到测不出"，是代数恒等。       │
   │   所以这一项对 TestSpatialProcessingKeepsMonoFoldFlat 与        │
   │   TestSurroundMonoFoldDownIsUsable 是**零风险**的。             │
   │                                                                │
   │   只动 mid 不动 side：中置的人声/底鼓/贝斯绕着走，            │
   │   而本来就铺在两侧的内容留在原地 —— 摆的是"音乐"，            │
   │   不是把整个立体声场揉成一团。                                 │
   └────────────────────────────────────────────────────────────────┘

   ┌─ 反射延迟摆动（ITD）──────────────────────────────────────────┐
   │                                                                │
   │   dL_k(t) = dL_k - Δ·s(t)      dR_k(t) = dR_k + Δ·s(t)        │
   │                                                                │
   │   ★ 这一项**动的是延迟**，所以它对单声道折叠不是恒等的 ——     │
   │   折叠里混着相位在扫的反射分量。这就是它被限制在早期反射场     │
   │   （能量约 -18dB）而不是直达声上的原因：                        │
   │                                                                │
   │     · 直达声上的延迟调制 = **不能碰**。哪怕两耳延迟相同，     │
   │       TestSurroundMonoFoldDownIsUsable 用的是"投影到原频率的   │
   │       幅度"，延迟在扫就等于相位在扫，投影会被抵消到接近 0 ——   │
   │       测出来的折叠会塌成负无穷，而真实的折叠幅度其实没变。     │
   │       （这是"探针与被测量不匹配"的又一个例子。）               │
   │     · 反射场只有 -18dB，它对折叠的贡献本来就 ≤ ±0.4·mid，      │
   │       相位扫动把这部分抹平，落在判据 [-10, +2] dB 之内。       │
   │                                                                │
   │   ★ 幅度 0.6ms/耳：抽头 1 的两耳差是 0.7ms，摆幅 ±1.2ms 之后   │
   │   它会**穿过 0** —— 也就是说最强的那个反射会真的从左摆到右，    │
   │   这才是"转圈"而不是"原地抖"。                                  │
   │   0.6ms ≈ 26 样本 @44.1kHz，最慢的延迟变化率折合约 3 音分，     │
   │   远低于可闻的音高调制门限，不会听成颤音。                       │
   └────────────────────────────────────────────────────────────────┘

   --------------------------------------------------------------------------
   二、分数延迟（fractional delay）

   延迟量是**连续**变化的，但环形缓冲的下标是整数。直接对下标取整
   会让输出在每次跨过一个样本时跳一次 —— 跳变量是"相邻两个样本之差"，
   对 3.6kHz 带限的反射信号大约是幅度的 0.5 倍，乘上抽头增益后仍有
   几十个 LSB —— 那就是能听见的"滋啦"（zipper noise）。

   所以读取用**线性插值**：相邻两个样本之间插一个分数。
   orbit = 0（本段关闭）时分数恒为 0，退化成逐位精确的整数读取 ——
   这保证了关掉环绕档之后的输出与本文件存在之前**完全一致**。

   --------------------------------------------------------------------------
   三、为什么用 sin 一个相位、而不是给每个环节各起一个

   摆动声像与反射延迟必须**同相**：声源在左边时，直达声左耳更响、
   反射也左耳先到。相位错开的话，两组线索互相打架，听感是
   "声音在左、空间在右"的撕裂感，比完全不动还糟。
   所以整个文件只有一个 LFO，两个环节都读它。

   频率取 0.25Hz（4 秒一圈）：
     · 更快（>0.5Hz）会被听成"自动声像在抖"，而不是"在绕"；
     · 更慢（<0.1Hz）用户切完档几秒内察觉不到它在动，
       等于又回到"静态"这条反馈上。
   ========================================================================== */

package audioplay

import "math"

/* --------------------------------------------------------------------------
   调制常量
   -------------------------------------------------------------------------- */

const (
	// orbitPeriodSeconds 是绕一圈的时长（秒），0.25Hz。
	//
	// 这是**唯一**决定"转多快"的常量。想改手感就改它：
	// 3 秒更活跃、6 秒更从容，再往两边就会分别掉进"抖"和"看不出在动"。
	orbitPeriodSeconds = 4.0

	// orbitPanDepth 是摆动声像的深度 K（0..1）。
	//
	// K = 0.45 → 摆到极端时左右耳响度比 (1.45)/(0.55) ≈ 2.6（7.4dB）。
	// 再大虽然更明显，但 mid 被推到 1.45 倍之后，叠加全通注入与
	// 混响就容易顶进软限幅（x > 1.48 时输出会连续钉在满幅上，
	// TestChainNoClippingWithExtremeInput 抓的就是这个）。
	orbitPanDepth = 0.45

	// orbitShiftMs 是反射延迟的**每耳**摆幅（毫秒）。
	//
	// 每耳摆 ±0.6ms ⇒ 两耳的时间差摆 ±1.2ms。
	// 抽头 1 的基准差是 0.7ms，摆动之后落在 [-0.5, 1.9] ms —— 会穿过 0，
	// 也就是最强的那个反射真的会从左耳转到右耳。
	orbitShiftMs = 0.6
)

/* --------------------------------------------------------------------------
   orbitLFO
   -------------------------------------------------------------------------- */

// orbitLFO 是环绕档唯一的调制源。
//
// ★ 它挂在 **Chain** 上而不是挂在某条链路（chainState）上：
// 档位切换时两条链要交叉淡化，如果各自持有一个 LFO，淡入链与淡出链
// 的相位不同 —— 30ms 里声像会从一个位置平移到另一个位置，
// 听感是切换瞬间"嗖"地扫了一下。共用一个相位，两条链算出的摆动量
// 完全相同，交叉淡化就只是两条信号的混合，没有任何额外运动。
//
// ★ 只在真的在处理音频时推进（processSingle / processFading）。
// 关掉音效的快速旁路路径不推进 —— 那会让相位停在原地，
// 下次开启时从一个随机位置起步。这没关系：新链是靠 30ms 交叉淡化
// 淡入的，起点相位是多少都被淡化盖住了。
type orbitLFO struct {
	phase float64
	inc   float64
}

// prepare 按采样率算相位步长，并把相位归零。
func (o *orbitLFO) prepare(sampleRate int) {
	fs := float64(sampleRate)
	if fs <= 0 {
		fs = 44100
	}
	o.inc = 2 * math.Pi / (orbitPeriodSeconds * fs)
	o.phase = 0
}

// next 推进一步并返回 sin 值（-1..1）。
func (o *orbitLFO) next() float64 {
	if o.inc <= 0 {
		return 0
	}
	v := math.Sin(o.phase)
	o.phase += o.inc
	if o.phase >= 2*math.Pi {
		o.phase -= 2 * math.Pi
	}
	return v
}

// applyOrbitPan 把中置分量按 s 摆动到左右耳之间。
//
// ★ 单声道折叠**恒等**（L + R = 2·mid），与 s 无关 —— 见文件头第一节。
// 这是它能放在链尾、又不碰任何折叠判据的根本原因。
//
// ★ 只动 mid、不动 side：中置内容（人声、底鼓、贝斯）绕着走，
// 本来就铺开的两侧内容留在原地。整个立体声场一起平移的话，
// 听感是"整块在左右滑"，而不是"音乐在绕"。
func applyOrbitPan(xl, xr, s float64) (float64, float64) {
	d := (xl + xr) * 0.5 * orbitPanDepth * s
	return xl + d, xr - d
}
