/**
 * 节点排布策略（歌词 → 世界坐标）
 *
 * 两条原则：
 *   1. **一句歌词 = 一个节点**，节点下标与 lyrics().index 严格一一对应
 *      （连空文本的行也不能跳过，否则行号会错位）；
 *   2. **间距由时间间隔决定**：两句贴得近就摆得近，隔得久才允许飞远 ——
 *      这样运镜时间永远短于演唱间隔，动画跟得上节拍。
 *
 * 分段（主歌 / 预副歌 / 副歌 / 桥段 / 尾奏）仍然会算，但只用来：
 *   · 在 HUD 上标当前段落；
 *   · 指定少数几处定点运镜（副歌第一句 rotate、最后一段 zoomOut 回阵心）。
 */
export const LAYOUT = {
  /** ★ 手调数组：给了就完全按它排（lyric 可省略，按 index 对应第几行） */
  nodes: null,

  /* ------------------------------------------------------------------------
     路径：**一句歌词 = 一个节点，间距由「这一句与上一句的时间间隔」决定**
     ------------------------------------------------------------------------
     动画是跟得上节拍才好看：两句贴得近，镜头就只挪一点点（快切）；
     隔得久，才允许飞远一点（大跳转）。于是间距不再由“段”硬跳出来，
     而是  step = clamp(stepMin, stepPerSec × 间隔秒, stepMax)。
     ------------------------------------------------------------------------ */
  /** 相邻两句的最小间距（世界单位）：间隔再短也不会叠在一起 */
  stepMin: 820,
  /** 每 1 秒时间间隔折算成多少世界单位 */
  stepPerSec: 430,
  /** 常规间距上限：再长的间隔也不至于把镜头甩飞、把动画拖没 */
  stepMax: 3200,
  /** 间隔 ≥ bridgeGapSec（真正的长留白）→ 允许拉到这么远，做出孤星的距离感。
   *  上限受 radiusMax 约束（对侧最远 = 两侧半径之和），所以 ≤ radiusMax + radiusMin */
  stepBridge: 4600,

  /* ------------------------------------------------------------------------
     半径带：整首歌沿一条**平滑鼓起**的螺旋排（内圈 → 中段外扩 → 收回内圈）。
     半径是连续函数，所以两节点的直线距离≈ 上面的 step —— 距离可控是这么来的。
     ------------------------------------------------------------------------ */
  radiusMin: 800,
  radiusMax: 4200,

  /* ---- 分段：只用于 HUD 的段落标签与入场运镜，**不再决定坐标** ---- */
  /** 歌词间隔超过这个秒数 → 分段 */
  sectionGapSec: 6,
  /** 没有大间隔时，每几行算一段（决定段落标签的长度） */
  maxSectionLines: 5,
  /** 间隔超过这个秒数 → 这段是「孤立的桥段」 */
  bridgeGapSec: 13,
  /** 段角色循环（最后一段强制以「回到阵心」收尾） */
  roleCycle: ["verse", "pre", "chorus"],
  /** 每种角色的默认镜头缩放（实际 zoom 还会按歌词长度微调，见 render） */
  zoomByRole: {
    verse: 1.0,
    pre: 0.95,
    chorus: 1.15,
    bridge: 0.82,
    outro: 0.7,
    center: 0.62,
    solo: 0.62,
  },
  /** 歌词最后一句永远落回阵心 (0,0)：整趟旅程“飞回中心”收束 */
  returnToCenter: true,
};

/**
 * 运镜类型与时长（秒）—— 转场就是运镜，两者是同一件事。
 *
 * ★ 选哪条**按时间间隔分档**，不按“看起来多远”：
 *   [0, gapDash)      → dash   快切（绝不拉远，短间隔才跟得上唱速）
 *   [gapDash, gapArc) → arc    弧线飞行
 *   [gapArc, ∞)       → zoomOut 拉远俯瞰 → 平移 → 聚焦（**只给长间隔**）
 *   外加三条定点：pan（几乎原地）/ rotate（副歌第一句）/ pass（情绪爆点）
 */
export const TRANSITIONS = {
  /** 几乎原地：轻轻滑一下就行 */
  pan: { dur: 0.35 },
  /** 短间隔：快切 —— 前 70% 加速冲、后 30% 刹住，带一点点推镜 punch */
  dash: { dur: 0.5 },
  /** 中等间隔：二次贝塞尔弧线，飞行途中 zoom 先缩后放 */
  arc: { dur: 1.05 },
  /** 长间隔：三段式（拉到俯瞰 → 平移到目标上方 → 压回聚焦） */
  zoomOut: { dur: 1.9 },
  /** 副歌第一句：绕目标公转切入 */
  rotate: { dur: 0.9 },
  /** 情绪爆点：直接穿过旧节点，中途白闪 */
  pass: { dur: 1.0 },

  /** 间隔分档（秒） */
  gapDash: 3.5,
  gapArc: 6.5,
  /** 两节点世界距离小于它 → 只平移（dash 都省了） */
  panMax: 520,

  /**
   * 提前量：镜头要比这一句**开口早到**，提前量 = 间隔 × leadRatio
   * 夹在 [leadMin, leadMax] 之间。转场时长直接用提前量，
   * 于是「唱到这句的时候镜头已经停稳、字也拼完了」。
   */
  leadRatio: 0.4,
  leadMin: 0.3,
  leadMax: 1.25,

  /** 穿越式的白闪强度与窗口（相对进度 0..1）。
   *  窗口 = 2×flashWidth × 时长；0.16 → 1.0s 的运镜里亮 320ms，
   *  既够“情绪爆点”，也够慢到能被眼睛接住（0.12 时只闪 240ms，太快） */
  flashPeak: 0.5,
  flashWidth: 0.16,
};

