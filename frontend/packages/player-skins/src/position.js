/* ==========================================================================
   position.js — 「播放位置不许回退」的稳态器（逐字歌词共用）
   --------------------------------------------------------------------------
   真实报障：逐字歌词播放时，已经点亮的那个字会周期性被**取消**、
   再过几十毫秒又**重新点亮**（观感是边界处闪一下）。

   根因在位置上，不在歌词数据上：后端的播放位置来自音频引擎的
   `Position()`，它是**按音频缓冲块**推进的（48kHz / 1024 帧 ≈ 21ms 一跳），
   而渲染侧拿到一个锚点后是按**墙钟**连续外推的。于是每来一次新的进度
   （宿主约 4Hz），对齐到的引擎位置可能比上一帧外推值**小半块**：
   填充边界往回退 0~21ms —— 落在这段里的那个字就被取消再重亮。

   两次修正（都在消费侧，不改数据）：
     · 逐字渲染器（lyrics-view / fx-lyrics / 桌面歌词窗 / 画布类样式）
       一律经过本函数，把「小幅回退」吸附住。
     · 宿主 audio.js 的 livePosition() 也用同一份规则，保证 `patch.position`
       本身单调（进度条、桌面歌词、整窗背景都跟着受益）。

   ★ 大幅回退不是抖动，是**用户 seek / 换歌重来**：必须照单全收，
   否则歌词会冻在旧位置上等歌追上来。两者的分界是本文件的 POSITION_HOLD_MS。
   ========================================================================== */

/**
 * 回退幅度不超过这个值（毫秒）就当成「引擎位置量化抖动」，吸附到上一次的位置。
 *
 * 为什么是 300：真实的量化误差上限是一个音频缓冲块（约 21ms），
 * 加上事件运输与主线程排队的抖动也远小于它；而人手 seek 的精度不会小于
 * 300ms（拖进度条最细也在一秒量级，方向键一下是 5s）。取一个远大于抖动、
 * 又远小于正常 seek 的量，两边都不会误判。
 */
export const POSITION_HOLD_MS = 300;

/**
 * 把「下一个位置」夹成不会倒退的位置。
 *
 * @param {number} prev 上一次**已经画出去**的位置（-1 / 非有限数 = 还没有）
 * @param {number} next 这次拿到的位置（宿主补丁 / 外推值 / 快照）
 * @returns {number} 实际应该显示的位置
 */
export function steadyPosition(prev, next) {
  const p = Number(prev);
  const n = Number(next);
  // 位置读不出来（宿主还没推过 progress / 切歌途中）：沿用上一次，别无中生有
  if (!Number.isFinite(n)) return Number.isFinite(p) && p >= 0 ? p : 0;
  if (!Number.isFinite(p) || p < 0) return n;
  if (n >= p) return n;
  // 小幅回退 = 引擎位置按缓冲块推进造成的对齐抖动：吸附，别让边界倒退
  if (p - n <= POSITION_HOLD_MS) return p;
  // 大幅回退 = seek / 换歌：接受新位置
  return n;
}
