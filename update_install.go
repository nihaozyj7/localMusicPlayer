/* ==========================================================================
   update_install.go — 把下载好的安装包换成正在运行的程序
   --------------------------------------------------------------------------
   这是整个更新功能里唯一有「弄坏用户程序」风险的环节，所以先把约束写清楚。

   为什么不能直接 os.Rename 覆盖自己：
     Windows 上正在运行的 exe 被内核锁住，任何写入/改名都会失败
     （ERROR_SHARING_VIOLATION），而且**不能自己解锁**。
     所以必须借助一个外部进程：本进程退出后，由它把新 exe 覆盖上去。

   为什么用 .bat 而不是「复制一个 helper.exe」：
     1. 绿色版要尽量小，多带一个 helper 二进制不值得；
     2. cmd.exe 一定存在，而且这段逻辑只有十几行；
     3. 关键点是**等本进程退出**——用 `tasklist` 轮询自己就行，
        不需要任何额外依赖。

   安全要点（每条都对应一个真实会踩的坑）：
     · 路径必须加引号：路径里有空格（"Program Files"、中文用户名下的目录）时，
       不加引号会被拆成多个参数，脚本会去操作一个根本不存在的路径；
     · 脚本要**先等进程退出再替换**：抢跑会失败，而失败时用户已经
       关了程序，看到的是「程序没了，更新也没成功」；
     · 替换前先备份旧 exe，替换失败时能回滚 —— 否则一旦新文件是坏的，
       用户手上就只剩一个跑不起来的程序、和一段看不懂的报错；
     · 成功后要重新启动新版本，而不是留用户对着一片空白的桌面。

   ★ 脚本正文只允许 ASCII，路径与参数一律走环境变量
   --------------------------------------------------------------------------
   cmd.exe **按控制台代码页解码 .bat 的字节**，而中文用户目录（
   `C:\Users\某某\Desktop\项目合集\音乐播放器\bin\`）是常态。历史实现是把
   路径直接拼进脚本正文的，于是 UTF-8 字节被按 CP936 解码：
     · `if exist` / `move` / `copy` 拿到的是乱码路径，报
       "The filename, directory name, or volume label syntax is incorrect."；
     · 多字节字符还会吃掉后面的字节、把两行命令粘成一行（连 `rem` 注释
       都会变成一条被执行的命令）。
   实测故障表现：更新脚本跑完，程序目录里**只剩一个 `lmplayer.exe.old`** ——
   `move` 侥幸成功、`copy` 与回滚都失败，用户既没有新版本、也起不来旧版本。

   环境块是 UTF-16 的，与代码页无关：所以路径/参数只出现在环境变量里
   （见 installEnv），脚本正文只出现变量名。正文里出现任何非 ASCII 字节
   都是 bug —— update_install_test.go 里有守卫用例（TestInstallScriptIsASCII）。
   ========================================================================== */

// installPlan 描述一次「用某个文件替换当前程序」的全部输入。
type installPlan struct {
	// SourcePath 是下载并校验通过的安装包。
	SourcePath string
	// TargetPath 是当前正在运行的可执行文件。
	TargetPath string
	// ScriptPath 是要写出的引导脚本。
	ScriptPath string
	// RestartArgs 是重启新版本时透传的命令行参数。
	RestartArgs []string
}

// 传给引导脚本的环境变量名。脚本正文只认这四个名字（见 buildInstallScript），
// 值一律原样放入、**不做任何转义** —— 转义是「写进脚本正文」才需要的东西。
const (
	envUpdateSrc  = "LM_UPDATE_SRC"
	envUpdateDst  = "LM_UPDATE_DST"
	envUpdateBak  = "LM_UPDATE_BAK"
	envUpdateArgs = "LM_UPDATE_ARGS"
)

// installEnv 把 plan 里的路径与参数组装成环境变量。
//
// 这些值就是「原来会被拼进脚本正文」的东西。之所以改走环境块：
//   - 环境块是 UTF-16，中文路径、`%`、`&` 都不会被代码页改写；
//   - 展开后的文本只在**带引号的使用点**出现（`"%LM_UPDATE_DST%"`），
//     引号让 `&`、`%` 都变回普通字符；唯一没引号的是 `start` 后面的参数串，
//     它自己已经是 `"a" "b"` 的形状。
func installEnv(plan installPlan) []string {
	return []string{
		envUpdateSrc + "=" + plan.SourcePath,
		envUpdateDst + "=" + plan.TargetPath,
		envUpdateBak + "=" + plan.TargetPath + ".old",
		envUpdateArgs + "=" + formatArgs(plan.RestartArgs),
	}
}

// buildInstallScript 生成 Windows 上的替换脚本（.bat）。
//
// 用 CRLF 行尾：cmd.exe 对 LF-only 的批处理文件在某些情况下会解析出错
// （尤其是带 goto/label 的脚本），这是 Windows 批处理的经典坑。
//
// ★ 正文里只能有 ASCII（见文件头），路径全部来自 %LM_UPDATE_*%。
func buildInstallScript(plan installPlan) string {
	var lines []string
	lines = append(lines,
		"@echo off",
		// 只影响控制台输出：正文是 ASCII，改代码页不会改变它的解码结果，
		// 但失败提示里带中文路径，控制台需要按 UTF-8 显示才不是乱码。
		"chcp 65001 >nul 2>&1",
		// 显式关掉延迟展开：`!` 在延迟展开下是特殊字符，而 Windows 文件名里
		// 允许出现 `!`。默认虽然就是关的，但注册表
		// HKCU\Software\Microsoft\Command Processor\DelayedExpansion=1
		// 会让每个 cmd 实例都打开它，setlocal 继承该状态 —— 写死了才不靠用户环境。
		"setlocal DisableDelayedExpansion",
		"rem ===== LMPlayer update helper (safe to delete) =====",
		"rem Generated by LMPlayer: wait for the running app to exit, swap the exe,",
		"rem restart it. Paths/arguments come from the environment:",
		"rem   LM_UPDATE_SRC / LM_UPDATE_DST / LM_UPDATE_BAK / LM_UPDATE_ARGS",
		"rem !! ASCII ONLY in this file !!  cmd.exe decodes a .bat with the console",
		"rem code page, so non-ASCII bytes here corrupt the script - the paths are",
		"rem deliberately not written into this file (see update_install.go).",
		"",
		"rem Wait until the old process releases the exe (about 60 s max).",
		"rem ping, not timeout: this process' stdin is NUL, and `timeout /t 1`",
		"rem returns INSTANTLY in that case - the loop would spin 60 times within",
		"rem a few milliseconds and then replace the exe while the app is still",
		"rem shutting down.",
		"set /a WAITED=0",
		":waitloop",
		fmt.Sprintf("tasklist /FI \"PID eq %d\" 2>nul | find \"%d\" >nul", os.Getpid(), os.Getpid()),
		"if errorlevel 1 goto ready",
		"set /a WAITED+=1",
		"if %WAITED% GEQ 60 goto ready",
		"ping -n 2 127.0.0.1 >nul",
		"goto waitloop",
		"",
		":ready",
		"rem Give the file lock a moment: process exit and handle release are not",
		"rem the same event.",
		"ping -n 2 127.0.0.1 >nul",
		"",
		"rem Back up the old version first, so a failed swap can be rolled back.",
		fmt.Sprintf("if exist \"%%%s%%\" del /f /q \"%%%s%%\" >nul 2>&1", envUpdateBak, envUpdateBak),
		fmt.Sprintf("if exist \"%%%s%%\" move /y \"%%%s%%\" \"%%%s%%\" >nul 2>&1", envUpdateDst, envUpdateDst, envUpdateBak),
		"",
		"rem copy, not move: the downloaded package stays where it is, so the user",
		"rem still has an intact file for a manual retry.",
		fmt.Sprintf("copy /y \"%%%s%%\" \"%%%s%%\" >nul 2>&1", envUpdateSrc, envUpdateDst),
		"if errorlevel 1 goto rollback",
		"",
		"rem Swap succeeded: drop the backup, start the new version.",
		fmt.Sprintf("del /f /q \"%%%s%%\" >nul 2>&1", envUpdateBak),
		fmt.Sprintf("start \"\" \"%%%s%%\" %%%s%%", envUpdateDst, envUpdateArgs),
		"goto cleanup",
		"",
		":rollback",
		"rem Swap failed: restore the backup, then tell the user what happened.",
		fmt.Sprintf("if exist \"%%%s%%\" move /y \"%%%s%%\" \"%%%s%%\" >nul 2>&1", envUpdateBak, envUpdateBak, envUpdateDst),
		"rem >CON, because this process' stdout is the null device: without it the",
		"rem console window stays empty and the user learns nothing at all. CON is",
		"rem opened at run time, i.e. after Windows gave this process a console.",
		">CON echo.",
		">CON echo   LMPlayer update failed: the program file was not replaced.",
		">CON echo   The previous version has been restored and still works.",
		">CON echo   Installer (double-click it to update by hand):",
		fmt.Sprintf(">CON echo     \"%%%s%%\"", envUpdateSrc),
		">CON echo.",
		"rem Keep the window on screen long enough to read. `pause` is useless",
		"rem here (stdin is NUL, so it returns immediately); ping is the",
		"rem stdin-independent way to wait.",
		"ping -n 21 127.0.0.1 >nul",
		"",
		":cleanup",
		"endlocal",
		"rem Self-delete: a script cannot delete itself while cmd is still reading",
		"rem it, so hand the deletion to a detached cmd (the `&` must be escaped,",
		"rem otherwise the outer cmd would run `del` right now).",
		"start /b \"\" cmd /c ping -n 2 127.0.0.1 >nul ^& del /f /q \"%~f0\"",
		"",
	)

	// 逐行 join 再统一补 CRLF，避免上面每条都要手写 \r\n。
	return strings.Join(lines, "\r\n") + "\r\n"
}

// formatArgs 把重启参数拼成 ` "a" "b"`（每个都加引号，含空格也不会被拆开）。
//
// 结果会作为环境变量的值传给脚本，脚本把它接在 `start` 后面 —— 参数里的
// 引号会破坏「一个参数一对引号」的形状，换行会让这一行提前结束，所以都清掉。
func formatArgs(args []string) string {
	if len(args) == 0 {
		return ""
	}
	var b strings.Builder
	for _, a := range args {
		clean := strings.NewReplacer(`"`, "", "\r", " ", "\n", " ").Replace(a)
		fmt.Fprintf(&b, " \"%s\"", clean)
	}
	return b.String()
}

// prepareInstall 写出引导脚本，返回它的路径。
//
// 它**不执行**任何替换动作，也不结束进程 —— 那些交给调用方，
// 因为「什么时候退出应用」是服务层与界面约定的时序。
func prepareInstall(plan installPlan) (string, error) {
	if strings.TrimSpace(plan.SourcePath) == "" {
		return "", fmt.Errorf("没有待安装的文件")
	}
	if _, err := os.Stat(plan.SourcePath); err != nil {
		return "", fmt.Errorf("待安装的文件不存在：%w", err)
	}
	if strings.TrimSpace(plan.TargetPath) == "" {
		return "", fmt.Errorf("无法定位当前程序路径")
	}
	// 这两个字符的环境变量值进到脚本后**没有**合法转义方式：
	//   · `"` 会闭掉 `"%LM_UPDATE_DST%"` 里的引号，让后面的内容变成新命令；
	//   · 换行会把这行批处理提前结束（剩下的半行会被当成命令执行）。
	// 与其赌它们不出现，不如在这里明确拒绝 —— 拒绝的代价是「这次更新没做」，
	// 放过去的代价是「脚本执行了半条被拼出来的命令」。
	for _, p := range []struct{ what, path string }{
		{"安装包路径", plan.SourcePath},
		{"程序路径", plan.TargetPath},
	} {
		if i := strings.IndexAny(p.path, "\"\r\n"); i >= 0 {
			return "", fmt.Errorf("%s里含有无法安全交给更新脚本的字符 %q：%s",
				p.what, p.path[i], p.path)
		}
	}

	script := buildInstallScript(plan)
	if err := os.WriteFile(plan.ScriptPath, []byte(script), 0o644); err != nil {
		return "", fmt.Errorf("写入更新脚本失败：%w", err)
	}
	return plan.ScriptPath, nil
}

// defaultInstallDir 返回存放「下载中的安装包」与引导脚本的目录。
//
// 放在数据目录下而不是系统临时目录：
//   - 系统临时目录可能被清理工具随时删掉，而这个文件在用户下次启动前
//     都必须存在（替换动作发生在进程退出之后）；
//   - 排查问题时用户能在自己的数据目录里找到那个安装包。
func defaultInstallDir(dataDir string) string {
	return filepath.Join(dataDir, "update")
}

// describeChannel 把通道 id 变成一句人话（安装完成后的提示里用到）。
func describeChannel(id string) string {
	if m, ok := update.MirrorByID(id); ok {
		if m.ID == "direct" {
			return "直连 GitHub"
		}
		return m.Name
	}
	return "自动选择"
}
